"""Template question fallback used when Gemini is temporarily unavailable.

Gemini (main.call_gemini_text) is replaced with scripted failures; these tests
prove the fallback contract and labelling, not the quality of real Gemini output.
"""

import json
import logging
import os

os.environ["AI_SERVICE_TOKEN"] = "test-token"

import pytest  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402

import app.main as main  # noqa: E402
from app.fallback_questions import BANK, build_fallback_questions  # noqa: E402

AUTH = {"X-Internal-Token": "test-token"}
client = TestClient(main.app)

AI_ML_JD = (
    "AI/ML Engineer. You will build and deploy machine learning models in Python using PyTorch and TensorFlow, "
    "work with pandas and NumPy for data pipelines, deploy on AWS with Docker, and build LLM features."
)


@pytest.fixture
def gemini(monkeypatch):
    state = {"replies": [], "prompts": []}

    def fake(prompt):
        state["prompts"].append(prompt)
        reply = state["replies"].pop(0)
        if isinstance(reply, tuple):
            return reply
        return json.dumps(reply), None

    monkeypatch.setattr(main, "call_gemini_text", fake)
    monkeypatch.setattr(main, "gemini_configured", lambda: True)
    return state


def ask(**extra):
    body = {"difficulty": "Medium", "category": "AI / Machine Learning", "count": 5, **extra}
    return client.post("/api/interview/guided/questions", json=body, headers=AUTH)


BUSY = (None, "Gemini request timed out (after 2 attempts; models tried: gemini-3.5-flash-lite, gemini-3.1-flash-lite)")


@pytest.mark.parametrize("count", [5, 10, 15, 20])
def test_transient_failure_returns_exactly_count_labelled_fallback_questions(gemini, count):
    gemini["replies"] = [BUSY]
    res = ask(count=count, job_description=AI_ML_JD)
    assert res.status_code == 200, res.text
    body = res.json()
    assert body["source"] == "fallback"
    assert body["fallback_reason"] == "Gemini was temporarily unavailable"
    questions = body["questions"]
    assert len(questions) == count
    assert len({q["question"] for q in questions}) == count, "no duplicates"
    assert all(q["difficulty"] == "Medium" and q["category"] == "AI / Machine Learning" for q in questions)
    assert all(set(q) == {"question", "category", "topic", "difficulty"} for q in questions), "same shape as Gemini questions"
    assert len(gemini["prompts"]) == 1, "no extra Gemini call after a transport failure"


def test_fallback_is_relevant_to_the_ai_ml_job_description(gemini):
    gemini["replies"] = [BUSY]
    questions = ask(count=10, job_description=AI_ML_JD).json()["questions"]
    text = " ".join(q["question"] for q in questions)
    assert "PyTorch" in text or "TensorFlow" in text, "uses skills detected in the job description"
    topics = {q["topic"] for q in questions}
    assert topics & {"pytorch", "tensorflow", "python", "pandas", "numpy", "aws", "docker", "machine learning", "llm"}
    ml_bank = set(BANK["AI / Machine Learning"])
    assert sum(q["question"] in ml_bank for q in questions) >= 5, "the rest are core AI/ML questions"


def test_fallback_is_logged_clearly_and_never_claims_gemini(gemini, caplog):
    gemini["replies"] = [(None, "Gemini HTTP 503: overloaded (after 3 attempts)")]
    with caplog.at_level(logging.WARNING, logger="rolefit.guided"):
        res = ask()
    assert res.status_code == 200
    assert res.json()["source"] == "fallback"
    assert "FALLBACK question set used" in caplog.text
    assert "NOT generated by Gemini" in caplog.text
    assert "503" in caplog.text, "the underlying Gemini error is logged"


def test_gemini_success_is_labelled_gemini(gemini):
    gemini["replies"] = [{"questions": [{"question": f"Explain ML concept number {i} please?", "category": "AI / Machine Learning", "topic": "ml"} for i in range(5)]}]
    body = ask().json()
    assert body["source"] == "gemini"
    assert "fallback_reason" not in body


@pytest.mark.parametrize("error", ["Gemini HTTP 400: invalid argument", "Gemini HTTP 403: permission denied", "Gemini HTTP 404: model not found"])
def test_no_fallback_for_non_transient_errors(gemini, error):
    """Bad key/model/request are configuration problems: surface them instead of hiding them."""
    gemini["replies"] = [(None, error)]
    res = ask()
    assert res.status_code == 502
    assert res.json()["detail"] == "The AI could not produce a valid question set. Please try again."


def test_no_fallback_for_malformed_gemini_output(gemini):
    gemini["replies"] = ["not json", "still not json"]
    assert ask().status_code == 502


def test_no_fallback_when_gemini_is_not_configured(monkeypatch):
    monkeypatch.setattr(main, "gemini_configured", lambda: False)
    assert ask().status_code == 503


def test_fallback_still_enforces_resume_and_jd_requirements(gemini):
    res = client.post("/api/interview/guided/questions", json={"difficulty": "Easy", "category": "Resume-Based Interview", "count": 5}, headers=AUTH)
    assert res.status_code == 422
    assert gemini["prompts"] == []


def test_evaluation_has_no_template_fallback(gemini):
    gemini["replies"] = [BUSY]
    res = client.post("/api/interview/guided/evaluate", json={"question": "What is overfitting?", "category": "AI / Machine Learning", "difficulty": "Easy", "transcript": "x"}, headers=AUTH)
    assert res.status_code == 502
    assert "Gemini is busy" in res.json()["detail"]


@pytest.mark.parametrize("category", [c for c in main.guided_interview.CATEGORIES])
@pytest.mark.parametrize("count", [5, 20])
def test_builder_fills_every_category_without_inputs(category, count):
    questions = build_fallback_questions(category, "Hard", count, [], [])
    assert len(questions) == count
    assert len({q["question"] for q in questions}) == count
    assert all(q["difficulty"] == "Hard" for q in questions)


def test_mixed_fallback_spreads_categories():
    questions = build_fallback_questions("Mixed Interview", "Easy", 10, [], [])
    assert len({q["category"] for q in questions}) >= 5


def test_builder_respects_avoid_list():
    first = build_fallback_questions("Behavioral", "Easy", 5, [], [])
    again = build_fallback_questions("Behavioral", "Easy", 5, [], [], avoid=[q["question"] for q in first])
    assert not {q["question"] for q in first} & {q["question"] for q in again}
